import { LANDING_PAGES, siblings } from '@/lib/landing-pages.js';

import { getStyle } from '@/services/catalog.js';
import { pageMeta, toMetadata, renderCards, inputFromQuery } from '@/lib/pages.js';
import { GeneratorInput } from '@/components/generator-input.jsx';
import { StyleRow } from '@/components/style-row.jsx';
import { JsonLd } from '@/components/json-ld.jsx';
import { Scripts } from '@/components/scripts.jsx';
import { Hero3D } from '@/components/hero-3d.jsx';
import { buildVariations } from '@/lib/emoji-variations.js';

function landingMeta(page, hasText) {
  return pageMeta({
    title: page.title,
    description: page.description,
    path: `/styles/${page.key}`,
    noindex: hasText,
    breadcrumbs: [
      { name: 'Home', path: '/' },
      { name: page.subject, path: `/styles/${page.key}` },
    ],
    faq: hasText ? [] : page.faq,
    app: !hasText,
  });
}

export function generateStaticParams() {
  return LANDING_PAGES.map((p) => ({ key: p.key }));
}

export async function generateMetadata({ params, searchParams }) {
  const { key } = await params;
  const page = LANDING_PAGES.find((p) => p.key === key);
  if (!page) return { robots: { index: false, follow: false } };
  const sp = (await searchParams) || {};
  return toMetadata(landingMeta(page, Boolean(sp.text)));
}

export async function renderLandingPage({ key, searchParams }) {
  const page = LANDING_PAGES.find((p) => p.key === key);
  if (!page) return null;

  const sp = (await searchParams) || {};
  const text = inputFromQuery(sp);
  const meta = landingMeta(page, Boolean(sp.text));

  // Only styles that actually exist in the catalog are rendered, so the page can
  // never advertise a style the engine cannot produce.
  const sections = page.sections
    .map((section) => {
      const styles = section.styles.map(getStyle).filter((s) => s && s.indexable);
      return { ...section, styles, cards: renderCards(styles, text) };
    })
    .filter((section) => section.styles.length > 0);

  const variations = buildVariations(page.variationSection.key, page.variationSection.subject, {
    source: `${page.key}:variation-section`,
  });

  const hero = sections[0];

  return (
    <>
      <JsonLd items={meta.jsonLd} />
      <Scripts pageKey="landing" generator />

      <nav className="crumbs" aria-label="Breadcrumb">
        <a href="/">Home</a> / <span aria-current="page">{page.subject}</span>
      </nav>

      <section className="hero">
        <Hero3D />
        <h1>{page.h1}</h1>
        {page.intro.map((paragraph, i) => (
          <p key={i} className={i === 0 ? 'lede' : 'muted'}>{paragraph}</p>
        ))}
        <GeneratorInput formAction={`/styles/${page.key}`} text={text} />
      </section>

      <section aria-labelledby="pick-a-style">
        <h2 id="pick-a-style">{hero.h2}</h2>
        <p className="muted">{hero.body}</p>
        <ul className="rows" data-rows>
          {hero.cards.map((s) => <StyleRow key={s.id} s={s} />)}
        </ul>
        <p className="more">
          <a href={`/?category=${hero.cards[0].category}`}>
            Browse every {page.subject.toLowerCase()} style in the generator
          </a>
        </p>
      </section>

      {sections.slice(1).map((section) => (
        <section key={section.h2} aria-labelledby={`section-${section.h2.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}`}>
          <h2 id={`section-${section.h2.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}`}>{section.h2}</h2>
          <p className="muted">{section.body}</p>
          <ul className="rows" data-rows>
            {section.cards.map((s) => <StyleRow key={s.id} s={s} />)}
          </ul>
        </section>
      ))}

      <section className="prose" aria-labelledby="field-limits">
        <h2 id="field-limits">Where this text works</h2>
        <p>
          Every style on this page is generated by the same Unicode engine as the main
          generator, so the output you see here is exactly what you copy. Support depends on
          the field you paste into, the app and the device — plain text fields accept the most
          characters, while username and display name fields are usually the most restrictive.
        </p>
        <p className="muted">
          Character limits are only stated where they are verified. Where we have not confirmed a
          limit, this page shows <code>No limit checked</code> rather than a number we cannot stand
          behind. Check the field itself before you commit to a name.
        </p>
      </section>

      <section aria-labelledby="variations-heading" className="variations">
        <h2 id="variations-heading">{page.variationSection.h2}</h2>
        <p className="muted">
          Search phrases people use for this page. Each one starts and ends with an emoji.
        </p>
        <ul className="chip-list">
          {variations.displayVariations.map((v) => (
            <li key={v.text} className="chip-phrase">{v.text}</li>
          ))}
        </ul>
      </section>

      <section className="prose" aria-labelledby="faq-heading">
        <h2 id="faq-heading">Frequently asked questions</h2>
        {page.faq.map((f) => (
          <div key={f.q}>
            <h3>{f.q}</h3>
            <p>{f.a}</p>
          </div>
        ))}
      </section>

      <nav className="crumbs" aria-label="Related pages">
        <h2>Related pages</h2>
        <ul className="chip-list">
          {page.links.map((l) => (
            <li key={l.href}><a href={l.href}>{l.label}</a></li>
          ))}
          {siblings(page.key).map((s) => (
            <li key={s.key}>
              <a href={`/styles/${s.key}`}>{s.subject}</a>
            </li>
          ))}
        </ul>
      </nav>
    </>
  );
}