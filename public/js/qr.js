// QR Code encoder — ISO/IEC 18004, Model 2, byte mode.
//
// Why not a library, in the same shape as the argument next door in
// image-compressor.js and zip.js: this project's client code is plain ES modules
// served out of /public under a CSP of `script-src 'self'`. There is no bundler
// to pull `qrcode` through and no CDN the policy allows, so the only honest
// options were a build step or this file. A build step to square 25 modules is a
// bad trade against a ~500-line, fully specified algorithm, so: here.
//
// Nothing in this module touches the DOM or the network. It takes a string and
// returns a module matrix, which is what makes it unit-testable under plain
// `node --test` against the same file the browser loads.
//
// Scope, stated plainly rather than implied:
//
// - Byte mode only. Every payload this page builds is a URL, a vCard, a Wi-Fi
//   string or plain text, all of which are byte data, and byte mode reads back
//   identically in every scanner. Numeric and alphanumeric modes would shrink a
//   short URL by a version or two and change nothing a scanner reads, so they
//   are not implemented rather than implemented and mis-tested.
// - Versions 1 to 40 at all four error-correction levels.
// - UTF-8 payload bytes, which is what every one of the ten QR types needs.
//
// Anything the standard does not define — a logo, colours, a quiet zone — is
// applied by the caller on top of the matrix, because none of it is part of the
// encoded symbol.

// ---- Error correction levels -------------------------------------------------
// The order the standard uses for the format-information field. Note that this
// is NOT the usual "L, M, Q, H" strength order: L is the weakest, H the
// strongest, but their *format bits* are L=1, M=0, Q=3, H=2. Getting this wrong
// produces a symbol that looks perfect and that no scanner will read.
export const ECC_LEVELS = {
  L: { order: 0, formatBits: 1, recovery: '7%' },
  M: { order: 1, formatBits: 0, recovery: '15%' },
  Q: { order: 2, formatBits: 3, recovery: '25%' },
  H: { order: 3, formatBits: 2, recovery: '30%' },
};

/** Error-correction codewords per block, indexed [level][version]. Version 0 unused. */
const ECC_CODEWORDS_PER_BLOCK = {
  L: [-1, 7, 10, 15, 20, 26, 18, 20, 24, 30, 18, 20, 24, 26, 30, 22, 24, 28, 30, 28, 28, 28, 28, 30, 30, 26, 28, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30],
  M: [-1, 10, 16, 26, 18, 24, 16, 18, 22, 22, 26, 30, 22, 22, 24, 24, 28, 28, 26, 26, 26, 26, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28, 28],
  Q: [-1, 13, 22, 18, 26, 18, 24, 18, 22, 20, 24, 28, 26, 24, 20, 30, 24, 28, 28, 26, 30, 28, 30, 30, 30, 30, 28, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30],
  H: [-1, 17, 28, 22, 16, 22, 28, 26, 26, 24, 28, 24, 28, 22, 24, 24, 30, 28, 28, 26, 28, 30, 24, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30],
};

/** Number of error-correction blocks, indexed [level][version]. Version 0 unused. */
const NUM_ERROR_CORRECTION_BLOCKS = {
  L: [-1, 1, 1, 1, 1, 1, 2, 2, 2, 2, 4, 4, 4, 4, 4, 6, 6, 6, 6, 7, 8, 8, 9, 9, 10, 12, 12, 12, 13, 14, 15, 16, 17, 18, 19, 19, 20, 21, 22, 24, 25],
  M: [-1, 1, 1, 1, 2, 2, 4, 4, 4, 5, 5, 5, 8, 9, 9, 10, 10, 11, 13, 14, 16, 17, 17, 18, 20, 21, 23, 25, 26, 28, 29, 31, 33, 35, 37, 38, 40, 43, 45, 47, 49],
  Q: [-1, 1, 1, 2, 2, 4, 4, 6, 6, 8, 8, 8, 10, 12, 16, 12, 17, 16, 18, 21, 20, 23, 23, 25, 27, 29, 34, 34, 35, 38, 40, 43, 45, 48, 51, 53, 56, 59, 62, 65, 68],
  H: [-1, 1, 1, 2, 4, 4, 4, 5, 6, 8, 8, 11, 11, 16, 16, 18, 16, 19, 21, 25, 25, 25, 34, 30, 32, 35, 37, 40, 42, 45, 48, 51, 54, 57, 60, 63, 66, 70, 74, 77, 81],
};

const MIN_VERSION = 1;
const MAX_VERSION = 40;

// Penalty weights from the standard's symbol-character-evaluation rules.
const PENALTY_N1 = 3; // runs of 5+ modules in one colour
const PENALTY_N2 = 3; // every 2x2 block of one colour
const PENALTY_N3 = 40; // finder-like 1:1:3:1:1 patterns
const PENALTY_N4 = 10; // deviation from a 50/50 dark-light balance

// ---- GF(256) ----------------------------------------------------------------
// Reed-Solomon works over the field generated by x^8 + x^4 + x^3 + x^2 + 1, which
// is 0x11D. Log/exp tables make a multiply a table index rather than a loop; the
// exp table is doubled to 512 entries so an index up to 508 can be read without
// a modulo.
const GF_EXP = new Uint8Array(512);
const GF_LOG = new Uint8Array(256);

(function initGaloisField() {
  let x = 1;
  for (let i = 0; i < 255; i += 1) {
    GF_EXP[i] = x;
    GF_LOG[x] = i;
    x <<= 1;
    if (x & 0x100) x ^= 0x11d;
  }
  for (let i = 255; i < 512; i += 1) GF_EXP[i] = GF_EXP[i - 255];
}());

function gfMul(a, b) {
  if (a === 0 || b === 0) return 0;
  return GF_EXP[GF_LOG[a] + GF_LOG[b]];
}

/**
 * The Reed-Solomon generator polynomial for `degree` parity symbols.
 *
 * Coefficients run highest power first, so the result is monic with the leading
 * entry set to 1, and it is built by repeatedly multiplying by (x - r^i).
 */
export function rsDivisor(degree) {
  const result = new Uint8Array(degree);
  result[degree - 1] = 1;
  let root = 1;
  for (let i = 0; i < degree; i += 1) {
    for (let j = 0; j < degree; j += 1) {
      result[j] = gfMul(result[j], root);
      if (j + 1 < degree) result[j] ^= result[j + 1];
    }
    root = gfMul(root, 0x02);
  }
  return result;
}

/** Polynomial remainder of `data` divided by `divisor`: the parity symbols. */
export function rsRemainder(data, divisor) {
  const result = new Uint8Array(divisor.length);
  for (let i = 0; i < data.length; i += 1) {
    const factor = data[i] ^ result[0];
    result.copyWithin(0, 1);
    result[result.length - 1] = 0;
    for (let j = 0; j < result.length; j += 1) {
      result[j] ^= gfMul(divisor[j], factor);
    }
  }
  return result;
}

/**
 * Syndromes of a Reed-Solomon codeword, evaluated at a^0..a^(n-k-1).
 *
 * Exported for the test suite. For a codeword the encoder produced correctly,
 * every syndrome is zero — which is the one check in the suite that verifies the
 * error-correction maths against the field itself rather than against this same
 * file's own opinion of it.
 */
export function rsSyndromes(codeword, degree) {
  const out = new Uint8Array(degree);
  for (let i = 0; i < degree; i += 1) {
    let acc = 0;
    for (let j = 0; j < codeword.length; j += 1) {
      acc = gfMul(acc, GF_EXP[i]) ^ codeword[j];
    }
    out[i] = acc;
  }
  return out;
}

// ---- Capacity ----------------------------------------------------------------

/**
 * Bits available for data and error correction at a version, before any
 * error-correction codewords are subtracted.
 *
 * Derived rather than tabulated: 16v^2 + 128v + 64 is the raw module count, from
 * which the alignment patterns, the version information (version 7 and up) and
 * the three finder patterns plus their separators are subtracted. Getting this
 * formula wrong shifts every capacity by a codeword somewhere in the middle of
 * the range, which is exactly the sort of bug a scanner rejects silently.
 */
export function getNumRawDataModules(version) {
  let result = (16 * version + 128) * version + 64;
  if (version >= 2) {
    const numAlign = Math.floor(version / 7) + 2;
    result -= (25 * numAlign - 10) * numAlign - 55;
    if (version >= 7) result -= 36;
  }
  return result;
}

/** Data codewords available at a version and error-correction level. */
export function getNumDataCodewords(version, ecl) {
  return Math.floor(getNumRawDataModules(version) / 8)
    - ECC_CODEWORDS_PER_BLOCK[ecl][version] * NUM_ERROR_CORRECTION_BLOCKS[ecl][version];
}

/** Centre coordinates of the alignment patterns, or none before version 2. */
function alignmentPatternPositions(version) {
  if (version === 1) return [];
  const numAlign = Math.floor(version / 7) + 2;
  // The centres are evenly spaced from 6 to size-7, and the spacing is the only
  // part of the layout the standard derives rather than tabulates (Annex E).
  // It has to be integer division followed by a multiply, not a rounded ratio:
  // versions 32 and 40 are where the two disagree, and a mis-spaced alignment
  // pattern is an unscannable symbol that still looks correct.
  // Version 32 is the one version the formula does not resolve, and the standard
  // gives its spacing directly.
  const step = version === 32
    ? 26
    : Math.floor(((version * 4 + numAlign * 2 + 1) / (numAlign * 2 - 2))) * 2;
  const result = new Array(numAlign);
  result[0] = 6;
  for (let i = numAlign - 1, pos = version * 4 + 17 - 7; i >= 1; i -= 1, pos -= step) {
    result[i] = pos;
  }
  return result;
}

/** Character-count indicator width for byte mode. */
const charCountBits = (version) => (version <= 9 ? 8 : 16);

// ---- Bit buffer --------------------------------------------------------------

class BitBuffer {
  constructor() {
    this.bits = [];
  }

  push(value, length) {
    for (let i = length - 1; i >= 0; i -= 1) {
      this.bits.push((value >>> i) & 1);
    }
  }

  get length() {
    return this.bits.length;
  }
}

const bytesToBits = (bytes) => {
  const out = new BitBuffer();
  for (let i = 0; i < bytes.length; i += 1) out.push(bytes[i], 8);
  return out.bits;
};

/** UTF-8 bytes. TextEncoder exists in every browser that runs ES modules and in Node. */
export function utf8Bytes(text) {
  if (typeof TextEncoder === 'function') return new TextEncoder().encode(text);
  // Fallback for a host with neither. Unreachable in practice, and a wrong
  // silent encoding would be worse than a crash, so it throws rather than guesses.
  throw new Error('This browser cannot encode text, so the QR code cannot be built.');
}

// ---- Segment + codewords -----------------------------------------------------

/**
 * The byte-mode segment: mode indicator, character count, then the bytes.
 *
 * 0b0100 is the byte-mode indicator. The character count is 8 bits up to version
 * 9 and 16 bits from version 10, which is why the version has to be known before
 * the segment can be built — and why version selection is a loop rather than a
 * single calculation.
 */
function buildDataCodewords(text, version) {
  const payload = utf8Bytes(text);
  const buffer = new BitBuffer();
  buffer.push(0b0100, 4);
  buffer.push(payload.length, charCountBits(version));

  const capacityBits = getNumDataCodewords(version, 'L') * 8;
  if (buffer.length + payload.length * 8 > capacityBits) {
    // Checked against level L because that is the loosest; the caller has
    // already rejected versions too small for the level it is actually using.
    throw new Error(`A ${payload.length}-byte value does not fit in a version ${version} code.`);
  }

  for (let i = 0; i < payload.length; i += 1) buffer.push(payload[i], 8);
  return buffer;
}

/** Terminator, byte alignment, and the alternating pad codewords. */
function finishDataCodewords(segmentBits, version, ecl) {
  const capacityBits = getNumDataCodewords(version, ecl) * 8;
  const bits = segmentBits.slice();

  const terminator = Math.min(4, capacityBits - bits.length);
  for (let i = 0; i < terminator; i += 1) bits.push(0);

  // Zero-pad to a whole codeword. The terminator alone rarely lands on a byte.
  for (let i = 0; i < (8 - (bits.length % 8)) % 8; i += 1) bits.push(0);

  const codewords = new Uint8Array(capacityBits / 8);
  for (let i = 0; i < bits.length; i += 8) {
    let byte = 0;
    for (let j = 0; j < 8; j += 1) byte = (byte << 1) | bits[i + j];
    codewords[i / 8] = byte;
  }

  // Pad with the two alternating bytes the standard specifies, so the remainder
  // of the capacity is filled with a known pattern rather than zeros. A scanner
  // does not check them, but a truncated or mis-sized code does look different.
  for (let i = bits.length / 8, pad = 0xec; i < codewords.length; i += 1) {
    codewords[i] = pad;
    pad ^= 0xec ^ 0x11;
  }
  return codewords;
}

/**
 * How a version and level split into blocks.
 *
 * Exported because the test suite needs it to take a symbol apart again, and
 * because it is the part of the encoding most easily got wrong: a symbol can be
 * self-consistent and still be unreadable if the blocks are split or ordered
 * differently from the standard.
 */
export function blockLayout(version, ecl) {
  const numBlocks = NUM_ERROR_CORRECTION_BLOCKS[ecl][version];
  const eccPerBlock = ECC_CODEWORDS_PER_BLOCK[ecl][version];
  const rawCodewords = Math.floor(getNumRawDataModules(version) / 8);
  return {
    numBlocks,
    eccPerBlock,
    rawCodewords,
    shortBlockLen: Math.floor(rawCodewords / numBlocks),
    numShortBlocks: numBlocks - (rawCodewords % numBlocks),
    dataCodewords: getNumDataCodewords(version, ecl),
  };
}

/**
 * Split into blocks, append parity symbols, and interleave.
 *
 * A version splits its codewords into 1 to 81 blocks depending on version and
 * level, and the blocks here differ in length by at most one symbol: the first
 * `numShortBlocks` are short, because `rawCodewords` rarely divides evenly by
 * `numBlocks`.
 *
 * The order is the part that is easy to get wrong. The final message is *all the
 * data codewords interleaved across the blocks, then all the parity codewords
 * interleaved across the blocks* — not each block's data and parity woven
 * together. Each block is therefore laid out with one spare slot between its
 * data and its parity, and that slot is skipped for the short blocks only; the
 * spare is what absorbs the one-symbol difference without disturbing the order.
 *
 * Weaving data and parity together instead still produces codewords that each
 * pass a Reed-Solomon syndrome check, and a decoder that inverts the same wrong
 * permutation will still read the payload back. It produces a symbol no scanner
 * agrees with, and it only shows up once a version has both short and long
 * blocks — which is why it survives a round-trip test.
 */
export function addEccAndInterleave(dataCodewords, version, ecl) {
  const numBlocks = NUM_ERROR_CORRECTION_BLOCKS[ecl][version];
  const blockEccLen = ECC_CODEWORDS_PER_BLOCK[ecl][version];
  const rawCodewords = Math.floor(getNumRawDataModules(version) / 8);
  const numShortBlocks = numBlocks - (rawCodewords % numBlocks);
  const shortBlockLen = Math.floor(rawCodewords / numBlocks);

  const divisor = rsDivisor(blockEccLen);
  const blocks = [];
  for (let i = 0, k = 0; i < numBlocks; i += 1) {
    const dataLen = shortBlockLen - blockEccLen + (i < numShortBlocks ? 0 : 1);
    const dat = dataCodewords.slice(k, k + dataLen);
    k += dataLen;
    const block = new Uint8Array(shortBlockLen + 1);
    block.set(dat, 0);
    block.set(rsRemainder(dat, divisor), shortBlockLen + 1 - blockEccLen);
    blocks.push(block);
  }

  const result = new Uint8Array(rawCodewords);
  let n = 0;
  const spare = shortBlockLen - blockEccLen;
  for (let i = 0; i < shortBlockLen + 1; i += 1) {
    for (let j = 0; j < numBlocks; j += 1) {
      if (i !== spare || j >= numShortBlocks) {
        result[n] = blocks[j][i];
        n += 1;
      }
    }
  }
  return result;
}

// ---- Matrix ------------------------------------------------------------------

class QrMatrix {
  constructor(version, ecl) {
    this.version = version;
    this.ecl = ecl;
    this.size = version * 4 + 17;
    this.modules = new Uint8Array(this.size * this.size);
    this.isFunction = new Uint8Array(this.size * this.size);
  }

  get(x, y) {
    return this.modules[y * this.size + x];
  }

  setFunctionModule(x, y, isDark) {
    this.modules[y * this.size + x] = isDark ? 1 : 0;
    this.isFunction[y * this.size + x] = 1;
  }

  drawFinderPattern(x, y) {
    // Chebyshev distance from the centre: 0 dark, 1 light, 2 dark ring, 3 light,
    // and 4 the separator that keeps the finder off the data.
    for (let dy = -4; dy <= 4; dy += 1) {
      for (let dx = -4; dx <= 4; dx += 1) {
        const dist = Math.max(Math.abs(dx), Math.abs(dy));
        const xx = x + dx;
        const yy = y + dy;
        if (xx >= 0 && xx < this.size && yy >= 0 && yy < this.size) {
          this.setFunctionModule(xx, yy, dist !== 2 && dist !== 4);
        }
      }
    }
  }

  drawAlignmentPattern(x, y) {
    for (let dy = -2; dy <= 2; dy += 1) {
      for (let dx = -2; dx <= 2; dx += 1) {
        this.setFunctionModule(x + dx, y + dy, Math.max(Math.abs(dx), Math.abs(dy)) !== 1);
      }
    }
  }

  drawFunctionPatterns() {
    const { size } = this;

    // Timing patterns: alternating modules along row 6 and column 6.
    for (let i = 0; i < size; i += 1) {
      this.setFunctionModule(6, i, i % 2 === 0);
      this.setFunctionModule(i, 6, i % 2 === 0);
    }

    this.drawFinderPattern(3, 3);
    this.drawFinderPattern(size - 4, 3);
    this.drawFinderPattern(3, size - 4);

    const positions = alignmentPatternPositions(this.version);
    const last = positions.length - 1;
    for (let i = 0; i <= last; i += 1) {
      for (let j = 0; j <= last; j += 1) {
        // The three corners already hold a finder pattern.
        const corner = (i === 0 && j === 0)
          || (i === 0 && j === last)
          || (i === last && j === 0);
        if (!corner) this.drawAlignmentPattern(positions[i], positions[j]);
      }
    }

    // Written once with a placeholder so the reserved modules are claimed, then
    // rewritten with the real mask once the mask has been chosen.
    this.drawFormatBits(0);
    this.drawVersion();
  }

  drawFormatBits(mask) {
    const data = (ECC_LEVELS[this.ecl].formatBits << 3) | mask;
    let rem = data;
    for (let i = 0; i < 10; i += 1) rem = (rem << 1) ^ ((rem >>> 9) * 0x537);
    const bits = ((data << 10) | rem) ^ 0x5412;
    const bit = (i) => ((bits >>> i) & 1) !== 0;

    // Copy 1, around the top-left finder pattern.
    for (let i = 0; i <= 5; i += 1) this.setFunctionModule(8, i, bit(i));
    this.setFunctionModule(8, 7, bit(6));
    this.setFunctionModule(8, 8, bit(7));
    this.setFunctionModule(7, 8, bit(8));
    for (let i = 9; i < 15; i += 1) this.setFunctionModule(14 - i, 8, bit(i));

    // Copy 2, split between the other two finders.
    for (let i = 0; i < 8; i += 1) this.setFunctionModule(this.size - 1 - i, 8, bit(i));
    for (let i = 8; i < 15; i += 1) this.setFunctionModule(8, this.size - 15 + i, bit(i));
    this.setFunctionModule(8, this.size - 8, true); // always dark
  }

  drawVersion() {
    if (this.version < 7) return;
    let rem = this.version;
    for (let i = 0; i < 12; i += 1) rem = (rem << 1) ^ ((rem >>> 11) * 0x1f25);
    const bits = (this.version << 12) | rem;

    for (let i = 0; i < 18; i += 1) {
      const dark = ((bits >>> i) & 1) !== 0;
      const a = this.size - 11 + (i % 3);
      const b = Math.floor(i / 3);
      this.setFunctionModule(a, b, dark);
      this.setFunctionModule(b, a, dark);
    }
  }

  drawCodewords(data) {
    let i = 0;
    for (let right = this.size - 1; right >= 1; right -= 2) {
      // Column 6 is the vertical timing pattern; the pair of columns steps over it.
      if (right === 6) right = 5;
      for (let vert = 0; vert < this.size; vert += 1) {
        for (let j = 0; j < 2; j += 1) {
          const x = right - j;
          const upward = ((right + 1) & 2) === 0;
          const y = upward ? this.size - 1 - vert : vert;
          if (!this.isFunction[y * this.size + x] && i < data.length * 8) {
            this.modules[y * this.size + x] = (data[i >>> 3] >>> (7 - (i & 7))) & 1;
            i += 1;
          }
        }
      }
    }
  }

  applyMask(mask) {
    for (let y = 0; y < this.size; y += 1) {
      for (let x = 0; x < this.size; x += 1) {
        if (this.isFunction[y * this.size + x]) continue;
        let invert;
        switch (mask) {
          case 0: invert = (x + y) % 2 === 0; break;
          case 1: invert = y % 2 === 0; break;
          case 2: invert = x % 3 === 0; break;
          case 3: invert = (x + y) % 3 === 0; break;
          case 4: invert = (Math.floor(x / 3) + Math.floor(y / 2)) % 2 === 0; break;
          case 5: invert = ((x * y) % 2) + ((x * y) % 3) === 0; break;
          case 6: invert = (((x * y) % 2) + ((x * y) % 3)) % 2 === 0; break;
          default: invert = (((x + y) % 2) + ((x * y) % 3)) % 2 === 0; break;
        }
        if (invert) this.modules[y * this.size + x] ^= 1;
      }
    }
  }
}

// ---- Mask penalty ------------------------------------------------------------

const newRunHistory = () => [0, 0, 0, 0, 0, 0, 0];

function finderPenaltyCountPatterns(runHistory) {
  const n = runHistory[1];
  const core = n > 0
    && runHistory[2] === n
    && runHistory[3] === n * 3
    && runHistory[4] === n
    && runHistory[5] === n;
  return (core && runHistory[0] >= n * 4 && runHistory[6] >= n ? 1 : 0)
    + (core && runHistory[6] >= n * 4 && runHistory[0] >= n ? 1 : 0);
}

/**
 * Push a finished run onto the seven-deep history.
 *
 * A line is scored as if it were surrounded by an imaginary light border of the
 * symbol's own width, which is what makes the finder-like 1:1:3:1:1 pattern at a
 * symbol's edge count the same as one in the middle.
 */
function finderPenaltyAddHistory(runLength, runHistory, size) {
  if (runHistory[0] === 0) runLength += size;
  runHistory.pop();
  runHistory.unshift(runLength);
}

/** Close the last run of a line and score the pattern it completes. */
function finderPenaltyTerminateAndCount(runColor, runLength, runHistory, size) {
  if (runColor) {
    // The symbol always ends light, so a trailing dark run is closed off first.
    finderPenaltyAddHistory(runLength, runHistory, size);
    runLength = 0;
  }
  runLength += size;
  finderPenaltyAddHistory(runLength, runHistory, size);
  return finderPenaltyCountPatterns(runHistory);
}

/** Rules 1 and 3 across one line, read at `get(index)`. */
function linePenalty(size, get) {
  let result = 0;
  let runColor = 0;
  let runLength = 0;
  const runHistory = newRunHistory();

  for (let i = 0; i < size; i += 1) {
    const dark = get(i);
    if (dark === runColor) {
      runLength += 1;
      if (runLength === 5) result += PENALTY_N1;
      else if (runLength > 5) result += 1;
      continue;
    }
    finderPenaltyAddHistory(runLength, runHistory, size);
    if (!runColor) result += finderPenaltyCountPatterns(runHistory) * PENALTY_N3;
    runColor = dark;
    runLength = 1;
  }
  return result + finderPenaltyTerminateAndCount(runColor, runLength, runHistory, size) * PENALTY_N3;
}

function penaltyScore(matrix) {
  const { size, modules } = matrix;
  let result = 0;

  // Rows first, then columns. The column pass indexes the transposed position
  // rather than materialising a transposed copy of the matrix.
  for (let y = 0; y < size; y += 1) {
    const base = y * size;
    result += linePenalty(size, (x) => modules[base + x]);
  }
  for (let x = 0; x < size; x += 1) {
    result += linePenalty(size, (y) => modules[y * size + x]);
  }

  // Rule 2: each 2x2 block of one colour.
  for (let y = 0; y < size - 1; y += 1) {
    for (let x = 0; x < size - 1; x += 1) {
      const c = modules[y * size + x];
      if (c === modules[y * size + x + 1]
        && c === modules[(y + 1) * size + x]
        && c === modules[(y + 1) * size + x + 1]) {
        result += PENALTY_N2;
      }
    }
  }

  // Rule 4: how far the dark/light ratio strays from 50%.
  let dark = 0;
  for (let i = 0; i < modules.length; i += 1) dark += modules[i];
  const total = size * size;
  const k = Math.ceil(Math.abs(dark * 20 - total * 10) / total) - 1;
  result += k * PENALTY_N4;

  return result;
}

// ---- Public API --------------------------------------------------------------

/**
 * Largest payload in bytes that fits at a version and level.
 *
 * Byte mode spends 4 bits on the mode indicator and `charCountBits(version)` on
 * the character count — one byte up to version 9, two from version 10 — so the
 * overhead is 2 codewords plus a third from version 10 up. Writing this as a flat
 * "-3" is off by a byte for every version below 10, which is exactly where most
 * short links and phone numbers land.
 */
export function byteCapacity(version, ecl) {
  return getNumDataCodewords(version, ecl) - 2 - (version <= 9 ? 0 : 1);
}

/**
 * Encode `text` as a QR symbol.
 *
 * Returns `{ version, ecl, mask, size, modules }`, where `modules` is a
 * size*size array of 0/1 in row-major order and `size` counts only symbol
 * modules — the quiet zone is not part of the symbol and is added by the
 * renderer, because the standard requires it and a QR without it is unscannable.
 *
 * Throws a readable message rather than returning a broken symbol: a QR code that
 * renders but does not scan is worse than an error, because the visitor has no
 * way to tell.
 */
export function encodeQr(text, { ecl = 'M', minVersion = MIN_VERSION, maxVersion = MAX_VERSION } = {}) {
  const level = ECC_LEVELS[ecl] ? ecl : 'M';
  const lo = Math.max(MIN_VERSION, minVersion);
  const hi = Math.min(MAX_VERSION, maxVersion);
  const value = String(text ?? '');

  if (!value) {
    // A symbol encoding zero bytes is legal and useless, and every caller here
    // has a field to ask about, so an empty value is a missing field rather than
    // a QR code. Refusing it stops an empty preview reaching a download button.
    throw new Error('There is nothing to encode yet.');
  }

  const bytes = utf8Bytes(value);

  // The character-count indicator is 8 bits up to version 9 and 16 bits after,
  // so version 9 and version 10 have different capacities for the same payload.
  // The cheapest fit is found by asking each version to build its own segment.
  let version = 0;
  let segmentBits = null;
  for (let v = lo; v <= hi; v += 1) {
    const countBits = charCountBits(v);
    const needed = (4 + countBits + bytes.length * 8 + 7) >> 3;
    if (bytes.length > (v <= 9 ? 255 : 65535)) continue;
    if (needed <= getNumDataCodewords(v, level)) {
      version = v;
      break;
    }
  }
  if (!version) {
    const biggest = byteCapacity(hi, level);
    throw new Error(
      `This value is ${bytes.length} bytes, which is too long for a QR code at error correction `
      + `${level} (the maximum is ${biggest}). Shorten the text, or use a lower error correction level.`,
    );
  }

  segmentBits = buildDataCodewords(value, version).bits;
  const dataCodewords = finishDataCodewords(segmentBits, version, level);
  const allCodewords = addEccAndInterleave(dataCodewords, version, level);

  // Each of the eight masks is drawn, scored, and the best one kept. Ties go to
  // the lowest mask number, which is what the standard's reference behaviour is.
  let best = null;
  for (let mask = 0; mask < 8; mask += 1) {
    const matrix = new QrMatrix(version, level);
    matrix.drawFunctionPatterns();
    matrix.drawCodewords(allCodewords);
    matrix.applyMask(mask);
    matrix.drawFormatBits(mask);
    const penalty = penaltyScore(matrix);
    if (!best || penalty < best.penalty) best = { matrix, mask, penalty };
  }

  return {
    version,
    ecl: level,
    mask: best.mask,
    size: best.matrix.size,
    modules: best.matrix.modules,
    isFunction: best.matrix.isFunction,
  };
}

// ---- Rendering helpers -------------------------------------------------------

const escapeXml = (value) => String(value).replace(/[<>&"']/g, (c) => ({
  '<': '&lt;',
  '>': '&gt;',
  '&': '&amp;',
  '"': '&quot;',
  "'": '&apos;',
}[c]));

/**
 * The dark modules as SVG path data, one `M x y h n v 1 h -n z` per horizontal
 * run rather than one rectangle per module.
 *
 * A version 10 symbol has 384 modules. One `<rect>` each is a 40 KB file that
 * every browser has to rebuild; merging horizontal runs takes a typical symbol
 * to about 60 path segments and a few kilobytes, with identical rendering. The
 * viewBox includes the quiet zone, which the standard requires to be four
 * modules wide on every side and which is absent from the matrix itself.
 */
export function qrPathData(qr, { quietZone = 4 } = {}) {
  const { size, modules } = qr;
  const parts = [];
  for (let y = 0; y < size; y += 1) {
    let x = 0;
    while (x < size) {
      if (!modules[y * size + x]) {
        x += 1;
        continue;
      }
      let run = 1;
      while (x + run < size && modules[y * size + x + run]) run += 1;
      parts.push(`M${x + quietZone} ${y + quietZone}h${run}v1h-${run}z`);
      x += run;
    }
  }
  return parts.join('');
}

/**
 * A standalone SVG document for a symbol.
 *
 * `width` and `height` in user units default to the pixel size the caller asked
 * for, and `shapeRendering="crispEdges"` stops the renderer blurring a module
 * edge at non-integer scales — a blurred edge is exactly the thing that costs a
 * scanner a code.
 */
export function qrToSvg(qr, {
  foreground = '#1b1533',
  background = '#ffffff',
  size = 512,
  quietZone = 4,
  title = '',
} = {}) {
  const extent = qr.size + quietZone * 2;
  const label = title
    ? `<title>${escapeXml(title)}</title>`
    : '';
  const role = title ? ' role="img"' : ' aria-hidden="true"';
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="${size}" height="${size}"`,
    ` viewBox="0 0 ${extent} ${extent}"${role} shape-rendering="crispEdges">`,
    label,
    `<rect width="${extent}" height="${extent}" fill="${escapeXml(background)}"/>`,
    `<path fill="${escapeXml(foreground)}" d="${qrPathData(qr, { quietZone })}"/>`,
    '</svg>',
  ].join('');
}

/**
 * WCAG 2.1 relative luminance of a `#rrggbb` colour.
 *
 * Used to keep the tool honest about contrast: a light-on-white QR code is
 * perfectly renderable and completely unscannable, and the only defence is to
 * measure it rather than eyeball it.
 */
export function relativeLuminance(hex) {
  const m = /^#?([\da-f]{6})$/i.exec(String(hex).trim());
  if (!m) return null;
  const n = parseInt(m[1], 16);
  const channel = (v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel((n >> 16) & 0xff)
    + 0.7152 * channel((n >> 8) & 0xff)
    + 0.0722 * channel(n & 0xff);
}

/**
 * Contrast ratio between two `#rrggbb` colours, from 1 to 21.
 *
 * The 4.5:1 threshold is the WCAG AA figure for body text. A QR code is not
 * text, and scanners tolerate rather less: the ratio here is reported to the
 * visitor as guidance rather than used to silently override their colour choice.
 */
export function contrastRatio(a, b) {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  if (la === null || lb === null) return null;
  const lighter = Math.max(la, lb);
  const darker = Math.min(la, lb);
  return (lighter + 0.05) / (darker + 0.05);
}

/** Read a `#rgb` or `#rrggbb` value as `#rrggbb`, or null if it is not one. */
export function normaliseHex(value) {
  const raw = String(value || '').trim();
  if (/^#?[\da-f]{3}$/i.test(raw)) {
    const [, h] = raw.match(/^#?(.{3})$/);
    return `#${h[0]}${h[0]}${h[1]}${h[1]}${h[2]}${h[2]}`.toLowerCase();
  }
  if (/^#?[\da-f]{6}$/i.test(raw)) return `#${raw.replace(/^#/, '')}`.toLowerCase();
  return null;
}
